const dictionaries: Record<Locale, Record<string, string>> = { en, hi, te };

interface I18nContextType {
  lang: Locale;
  t: (key: string, params?: Record<string, string | number>) => string;
  setLang: (lang: string) => void;
}

const I18nContext = createContext<I18nContextType>({
  lang: 'en',
  t: (k) => dictionaries.en[k] ?? k,
  setLang: () => {},
});

export function applyLanguage(lang: string) {
  if (typeof document === 'undefined') return;
  document.documentElement.lang = lang;
  localStorage.setItem('vidyguide_language', lang);
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const { settings, updateSettings, loading } = useSettings();

  const lang: Locale = (settings.language === 'hi' || settings.language === 'te' ? settings.language : 'en');

  useEffect(() => {
    applyLanguage(lang);
  }, [lang]);

  const t = useCallback((key: string, params?: Record<string, string | number>) => {
    const dict = dictionaries[lang] ?? en;
    let str = (dict as Record<string, string>)[key] ?? (en as Record<string, string>)[key] ?? key;
    if (params) {
      Object.entries(params).forEach(([k, v]) => {
        str = str.split(`{${k}}`).join(String(v));
      });
    }
    return str;
  }, [lang]);

  const setLang = useCallback((value: string) => {
    const locale: Locale = value === 'hi' || value === 'te' ? value : 'en';
    localStorage.setItem('vidyguide_language', locale);
    applyLanguage(locale);
    if (!loading) updateSettings({ language: locale });
  }, [updateSettings, loading]);

  const value = useMemo(() => ({ lang, t, setLang }), [lang, t, setLang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
